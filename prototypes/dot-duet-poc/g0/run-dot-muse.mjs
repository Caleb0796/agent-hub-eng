import { G0Store } from './store.mjs';
import { startServers } from '../src/server.mjs';
import { randomBytes, timingSafeEqual } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
const directory = resolve('.state/dot-muse');
mkdirSync(directory, {recursive:true,mode:0o700});
const credentialFile = join(directory,'connection-tokens.json');
if (!existsSync(credentialFile)) writeFileSync(credentialFile, JSON.stringify(Object.fromEntries(['dot','muse'].map(r=>[r,randomBytes(32).toString('base64url')]))), {mode:0o600});
const tokens = JSON.parse(readFileSync(credentialFile,'utf8'));
const store = new G0Store(directory,{participants:['dot','muse'],maxMessages:2});
store.connectionTokens=tokens;
store.authenticate=token=>Object.entries(tokens).find(([,v])=>v.length===token.length && timingSafeEqual(Buffer.from(v),Buffer.from(token)))?.[0];
const running=await startServers({directory,storeOverride:store});
console.log('Dot–Muse G0 relay: 127.0.0.1:8787; owner console: http://127.0.0.1:8788/g0');
setTimeout(async()=>{await running.stop();process.exit(0)},Math.max(1,store.data.expires-Date.now()));
for(const signal of ['SIGTERM','SIGINT']) process.once(signal,async()=>{await running.stop();process.exit(0)});
